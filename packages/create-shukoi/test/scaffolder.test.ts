/**
 * @purpose Unit tests for create-shukoi CLI scaffolder, dependency pruning, and flag parsing.
 * @rationale Ensures scaffoldProject prunes unneeded dependencies and generates valid boilerplate.
 * @preconditions Vitest test runner; temporary test directory.
 * @invariants Assertions must pass with exit code 0.
 */

import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { describe, expect, it } from 'vitest';
import { parseCliArgs, scaffoldProject } from '../src/index.js';

describe('create-shukoi Scaffolder', () => {
  it('correctly parses CLI arguments for automated non-interactive scaffolding', () => {
    const argv = [
      'my-service',
      '--products',
      'api,mcp-http',
      '--targets',
      'cloudflare,selfhost',
      '--pm',
      'pnpm',
    ];

    const parsed = parseCliArgs(argv);
    expect(parsed.projectName).toBe('my-service');
    expect(parsed.products).toEqual(['api', 'mcp-http']);
    expect(parsed.targets).toEqual(['cloudflare', 'selfhost']);
    expect(parsed.packageManager).toBe('pnpm');
  });

  it('scaffolds project on disk with strict dependency pruning', async () => {
    const tmpDir = await fs.mkdtemp(path.join(os.tmpdir(), 'shukoi-test-'));
    const projectName = 'pruned-service';

    const { projectDir, filesCreated } = await scaffoldProject({
      projectName,
      targetDir: tmpDir,
      products: ['api'], // only api selected
      targets: ['selfhost'], // only selfhost selected
      packageManager: 'pnpm',
    });

    expect(filesCreated).toContain('package.json');
    expect(filesCreated).toContain('tsconfig.json');
    expect(filesCreated).toContain('src/config.ts');
    expect(filesCreated).toContain('src/actions/health.ts');

    const pkgContent = await fs.readFile(path.join(projectDir, 'package.json'), 'utf-8');
    const pkg = JSON.parse(pkgContent);

    // License must be MIT
    expect(pkg.license).toBe('MIT');

    // Dependencies MUST include @shukoi/api and @shukoi/selfhost matching active version
    expect(pkg.dependencies['@shukoi/core']).toBe('^1.0.2');
    expect(pkg.dependencies['@shukoi/api']).toBe('^1.0.2');
    expect(pkg.dependencies['@shukoi/selfhost']).toBe('^1.0.2');

    // Dependencies MUST NOT include @shukoi/cloudflare, @shukoi/lambda, or @shukoi/mcp (PRUNED!)
    expect(pkg.dependencies['@shukoi/cloudflare']).toBeUndefined();
    expect(pkg.dependencies['@shukoi/lambda']).toBeUndefined();
    expect(pkg.dependencies['@shukoi/mcp']).toBeUndefined();

    // Biome linter MUST be generated by default
    expect(filesCreated).toContain('biome.json');
    expect(pkg.devDependencies['@biomejs/biome']).toBeDefined();
    expect(pkg.scripts['lint']).toBe('biome check .');

    // Entrypoints generated matching products and targets
    expect(filesCreated).toContain('src/entries/selfhost.ts');

    // AI context and skills MUST be generated by default
    expect(filesCreated).toContain('AGENTS.md');
    expect(filesCreated).toContain('CLAUDE.md');
    expect(filesCreated).toContain('skills/shukoi-create-action/SKILL.md');
    expect(filesCreated).toContain('skills/shukoi-quality-gates/SKILL.md');

    // Cleanup
    await fs.rm(tmpDir, { recursive: true, force: true });
  });

  it('omits biome.json and skips @biomejs/biome when --no-linter is supplied', async () => {
    const tmpDir = await fs.mkdtemp(path.join(os.tmpdir(), 'shukoi-test-no-linter-'));
    const projectName = 'no-linter-service';

    const parsed = parseCliArgs(['my-service', '--no-linter']);
    expect(parsed.includeLinter).toBe(false);

    const { projectDir, filesCreated } = await scaffoldProject({
      projectName,
      targetDir: tmpDir,
      products: ['api'],
      targets: ['selfhost'],
      packageManager: 'pnpm',
      includeLinter: false,
    });

    expect(filesCreated).not.toContain('biome.json');
    const pkgContent = await fs.readFile(path.join(projectDir, 'package.json'), 'utf-8');
    const pkg = JSON.parse(pkgContent);
    expect(pkg.devDependencies['@biomejs/biome']).toBeUndefined();
    expect(pkg.scripts['lint']).toBeUndefined();

    await fs.rm(tmpDir, { recursive: true, force: true });
  });

  it('scaffolds complete Cloudflare Workers project with wrangler.jsonc, env.d.ts, and dev scripts', async () => {
    const tmpDir = await fs.mkdtemp(path.join(os.tmpdir(), 'shukoi-test-cf-'));
    const projectName = 'cf-worker-service';

    const { projectDir, filesCreated } = await scaffoldProject({
      projectName,
      targetDir: tmpDir,
      products: ['api'],
      targets: ['cloudflare'],
      packageManager: 'pnpm',
    });

    // 1. Files created
    expect(filesCreated).toContain('wrangler.jsonc');
    expect(filesCreated).toContain('env.d.ts');
    expect(filesCreated).toContain('src/entries/cloudflare.ts');

    // 2. wrangler.jsonc contents
    const wranglerRaw = await fs.readFile(path.join(projectDir, 'wrangler.jsonc'), 'utf-8');
    const wranglerConfig = JSON.parse(wranglerRaw);
    expect(wranglerConfig.name).toBe('cf-worker-service');
    expect(wranglerConfig.main).toBe('src/entries/cloudflare.ts');
    expect(wranglerConfig.compatibility_flags).toContain('nodejs_compat');

    // 3. package.json devDependencies and scripts
    const pkgRaw = await fs.readFile(path.join(projectDir, 'package.json'), 'utf-8');
    const pkg = JSON.parse(pkgRaw);
    expect(pkg.devDependencies['wrangler']).toBeDefined();
    expect(pkg.devDependencies['@cloudflare/workers-types']).toBeDefined();
    expect(pkg.scripts['dev']).toBe('wrangler dev');
    expect(pkg.scripts['deploy']).toBe('wrangler deploy');
    expect(pkg.scripts['cf-typegen']).toBe('wrangler types env.d.ts');

    // 4. tsconfig.json types
    const tsconfigRaw = await fs.readFile(path.join(projectDir, 'tsconfig.json'), 'utf-8');
    const tsconfig = JSON.parse(tsconfigRaw);
    expect(tsconfig.compilerOptions.types).toContain('@cloudflare/workers-types');
    expect(tsconfig.include).toContain('env.d.ts');

    await fs.rm(tmpDir, { recursive: true, force: true });
  });

  it('scaffolds complete AWS Lambda project with template.yaml, esbuild, and dev scripts', async () => {
    const tmpDir = await fs.mkdtemp(path.join(os.tmpdir(), 'shukoi-test-lambda-'));
    const projectName = 'lambda-order-service';

    const { projectDir, filesCreated } = await scaffoldProject({
      projectName,
      targetDir: tmpDir,
      products: ['api'],
      targets: ['lambda'],
      packageManager: 'pnpm',
    });

    // 1. Files created
    expect(filesCreated).toContain('template.yaml');
    expect(filesCreated).toContain('src/entries/lambda.ts');

    // 2. template.yaml contents
    const samRaw = await fs.readFile(path.join(projectDir, 'template.yaml'), 'utf-8');
    expect(samRaw).toContain('Transform: AWS::Serverless-2016-10-31');
    expect(samRaw).toContain('Runtime: nodejs22.x');
    expect(samRaw).toContain('Handler: dist/lambda.mjs.handler');
    expect(samRaw).toContain('arm64');

    // 3. package.json devDependencies and scripts
    const pkgRaw = await fs.readFile(path.join(projectDir, 'package.json'), 'utf-8');
    const pkg = JSON.parse(pkgRaw);
    expect(pkg.devDependencies['@types/aws-lambda']).toBeDefined();
    expect(pkg.devDependencies['esbuild']).toBeDefined();
    expect(pkg.scripts['build:lambda']).toContain('esbuild src/entries/lambda.ts');
    expect(pkg.scripts['dev']).toBe('sam local start-api');
    expect(pkg.scripts['deploy']).toBe('sam deploy --guided');

    await fs.rm(tmpDir, { recursive: true, force: true });
  });

  it('scaffolds complete Self-Host project with Dockerfile, .dockerignore, and dev/start scripts', async () => {
    const tmpDir = await fs.mkdtemp(path.join(os.tmpdir(), 'shukoi-test-selfhost-'));
    const projectName = 'selfhost-core-service';

    const { projectDir, filesCreated } = await scaffoldProject({
      projectName,
      targetDir: tmpDir,
      products: ['api'],
      targets: ['selfhost'],
      packageManager: 'pnpm',
    });

    // 1. Files created
    expect(filesCreated).toContain('Dockerfile');
    expect(filesCreated).toContain('.dockerignore');
    expect(filesCreated).toContain('src/entries/selfhost.ts');

    // 2. Dockerfile contents
    const dockerfileRaw = await fs.readFile(path.join(projectDir, 'Dockerfile'), 'utf-8');
    expect(dockerfileRaw).toContain('FROM node:22-alpine AS builder');
    expect(dockerfileRaw).toContain('USER node');
    expect(dockerfileRaw).toContain('EXPOSE 3000');
    expect(dockerfileRaw).toContain('CMD ["node", "dist/entries/selfhost.js"]');

    // 3. .dockerignore contents
    const dockerignoreRaw = await fs.readFile(path.join(projectDir, '.dockerignore'), 'utf-8');
    expect(dockerignoreRaw).toContain('node_modules');
    expect(dockerignoreRaw).toContain('dist');

    // 4. package.json scripts
    const pkgRaw = await fs.readFile(path.join(projectDir, 'package.json'), 'utf-8');
    const pkg = JSON.parse(pkgRaw);
    expect(pkg.scripts['dev']).toBe('node --watch src/entries/selfhost.ts');
    expect(pkg.scripts['start']).toBe('node dist/entries/selfhost.js');

    await fs.rm(tmpDir, { recursive: true, force: true });
  });

  it('scaffolds selfhost entrypoint when products contains only mcp-http', async () => {
    const tmpDir = await fs.mkdtemp(path.join(os.tmpdir(), 'shukoi-test-selfhost-mcp-'));
    const projectName = 'mcp-selfhost-service';

    const { projectDir, filesCreated } = await scaffoldProject({
      projectName,
      targetDir: tmpDir,
      products: ['mcp-http'],
      targets: ['selfhost'],
      packageManager: 'pnpm',
    });

    expect(filesCreated).toContain('src/entries/selfhost.ts');
    const entryCode = await fs.readFile(path.join(projectDir, 'src/entries/selfhost.ts'), 'utf-8');
    expect(entryCode).toContain('createMcpHttpHandler');
    expect(entryCode).toContain('createSelfHostServer');

    await fs.rm(tmpDir, { recursive: true, force: true });
  });
});
