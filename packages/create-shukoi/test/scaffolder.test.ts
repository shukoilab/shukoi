/**
 * @purpose Unit tests for create-shukoi CLI scaffolder, dependency pruning, and flag parsing.
 * @rationale Ensures scaffoldProject prunes unneeded dependencies and generates valid boilerplate.
 * @preconditions Vitest test runner; temporary test directory.
 * @invariants Assertions must pass with exit code 0.
 */

import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { describe, expect, it } from 'vitest';
import { parseCliArgs, scaffoldProject } from '../src/index.js';

describe('create-shukoi Scaffolder', () => {
  it('correctly parses CLI arguments for automated non-interactive scaffolding', () => {
    const argv = [
      'my-service',
      '--products',
      'api,mcp-http',
      '--targets',
      'cloudflare,selfhost',
      '--pm',
      'pnpm',
    ];

    const parsed = parseCliArgs(argv);
    expect(parsed.projectName).toBe('my-service');
    expect(parsed.products).toEqual(['api', 'mcp-http']);
    expect(parsed.targets).toEqual(['cloudflare', 'selfhost']);
    expect(parsed.packageManager).toBe('pnpm');
  });

  it('scaffolds project on disk with strict dependency pruning', async () => {
    const tmpDir = await fs.mkdtemp(path.join(os.tmpdir(), 'shukoi-test-'));
    const projectName = 'pruned-service';

    const { projectDir, filesCreated } = await scaffoldProject({
      projectName,
      targetDir: tmpDir,
      products: ['api'], // only api selected
      targets: ['selfhost'], // only selfhost selected
      packageManager: 'pnpm',
    });

    expect(filesCreated).toContain('package.json');
    expect(filesCreated).toContain('tsconfig.json');
    expect(filesCreated).toContain('src/config.ts');
    expect(filesCreated).toContain('src/actions/health.ts');

    const pkgContent = await fs.readFile(path.join(projectDir, 'package.json'), 'utf-8');
    const pkg = JSON.parse(pkgContent);

    // License must be MIT
    expect(pkg.license).toBe('MIT');

    // Dependencies MUST include @shukoi/api and @shukoi/selfhost matching active version
    expect(pkg.dependencies['@shukoi/core']).toBe('^1.0.2');
    expect(pkg.dependencies['@shukoi/api']).toBe('^1.0.2');
    expect(pkg.dependencies['@shukoi/selfhost']).toBe('^1.0.2');

    // Dependencies MUST NOT include @shukoi/cloudflare, @shukoi/lambda, or @shukoi/mcp (PRUNED!)
    expect(pkg.dependencies['@shukoi/cloudflare']).toBeUndefined();
    expect(pkg.dependencies['@shukoi/lambda']).toBeUndefined();
    expect(pkg.dependencies['@shukoi/mcp']).toBeUndefined();

    // Biome linter MUST be generated by default
    expect(filesCreated).toContain('biome.json');
    expect(pkg.devDependencies['@biomejs/biome']).toBeDefined();
    expect(pkg.scripts['lint']).toBe('biome check .');

    // Entrypoints generated matching products and targets
    expect(filesCreated).toContain('src/entries/selfhost.ts');

    // AI context and skills MUST be generated by default
    expect(filesCreated).toContain('AGENTS.md');
    expect(filesCreated).toContain('CLAUDE.md');
    expect(filesCreated).toContain('skills/shukoi-create-action/SKILL.md');
    expect(filesCreated).toContain('skills/shukoi-quality-gates/SKILL.md');

    // Cleanup
    await fs.rm(tmpDir, { recursive: true, force: true });
  });

  it('omits biome.json and skips @biomejs/biome when --no-linter is supplied', async () => {
    const tmpDir = await fs.mkdtemp(path.join(os.tmpdir(), 'shukoi-test-no-linter-'));
    const projectName = 'no-linter-service';

    const parsed = parseCliArgs(['my-service', '--no-linter']);
    expect(parsed.includeLinter).toBe(false);

    const { projectDir, filesCreated } = await scaffoldProject({
      projectName,
      targetDir: tmpDir,
      products: ['api'],
      targets: ['selfhost'],
      packageManager: 'pnpm',
      includeLinter: false,
    });

    expect(filesCreated).not.toContain('biome.json');
    const pkgContent = await fs.readFile(path.join(projectDir, 'package.json'), 'utf-8');
    const pkg = JSON.parse(pkgContent);
    expect(pkg.devDependencies['@biomejs/biome']).toBeUndefined();
    expect(pkg.scripts['lint']).toBeUndefined();

    await fs.rm(tmpDir, { recursive: true, force: true });
  });
});
